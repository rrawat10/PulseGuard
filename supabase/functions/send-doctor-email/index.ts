serve(async (req) => {
  // Handle CORS preflight requests
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const emailData: EmailData = await req.json();
    console.log('Processing email request:', emailData);

    // Get user profile
    const { data: userProfile, error: profileError } = await supabase
      .from('user_profiles')
      .select('*')
      .eq('user_id', emailData.user_id)
      .single();

    if (profileError || !userProfile) {
      throw new Error('User profile not found');
    }

    // Check if doctor reports are enabled
    if (!userProfile.enable_doctor_reports) {
      return new Response(JSON.stringify({
        success: false,
        message: 'Doctor reports are disabled for this user'
      }), {
        status: 400,
        headers: { "Content-Type": "application/json", ...corsHeaders },
      });
    }

    // Get doctor details
    const { data: doctorDetails, error: doctorError } = await supabase
      .from('doctor_details')
      .select('*')
      .eq('user_id', emailData.user_id)
      .single();

    if (doctorError || !doctorDetails) {
      throw new Error('Doctor details not found');
    }

    let emailHtml = '';
    let subject = '';

    if (emailData.email_type === 'emergency_alert' && emailData.alert_id) {
      // Get emergency alert details
      const { data: alert, error: alertError } = await supabase
        .from('emergency_alerts')
        .select('*, pulse_readings(*)')
        .eq('id', emailData.alert_id)
        .single();

      if (alertError || !alert) {
        throw new Error('Emergency alert not found');
      }

      subject = `🚨 EMERGENCY ALERT - ${userProfile.full_name}`;
      emailHtml = generateEmergencyAlertEmail(userProfile, doctorDetails, alert, alert.pulse_readings);

    } else if (emailData.report_id) {
      // Get health report
      const { data: report, error: reportError } = await supabase
        .from('health_reports')
        .select('*')
        .eq('id', emailData.report_id)
        .single();

      if (reportError || !report) {
        throw new Error('Health report not found');
      }

      subject = `${report.report_type.charAt(0).toUpperCase() + report.report_type.slice(1)} Health Report - ${userProfile.full_name}`;
      emailHtml = generateHealthReportEmail(userProfile, doctorDetails, report, report.report_type);
    }

    // Send email
    const emailResponse = await resend.emails.send({
      from: 'Fit Beat <noreply@fitbeat.com>',
      to: [doctorDetails.email],
      subject: subject,
      html: emailHtml,
    });

    console.log('Email sent successfully:', emailResponse);

    return new Response(JSON.stringify({
      success: true,
      message: 'Email sent successfully to doctor',
      email_id: emailResponse.id
    }), {
      status: 200,
      headers: { "Content-Type": "application/json", ...corsHeaders },
    });

  } catch (error: any) {
    console.error('Error sending doctor email:', error);
    return new Response(JSON.stringify({
      error: error.message || 'Failed to send email'
    }), {
      status: 500,
      headers: { "Content-Type": "application/json", ...corsHeaders },
    });
  }
});